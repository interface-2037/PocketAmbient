#!/usr/bin/env python3
"""Generate the integer lookup tables shared by the C model, the composer and the RTL.

This is the only place floating point is used. Outputs are committed so normal
builds don't need Python:
  model/gen_tables.h               synth model tables (sine, wavetables, limiter)
  fw/composer/gen_ctables.h        composer tables (pitch, cents, sine, log2/exp2)
  src/fpga/core/synth/*.hex        same synth tables for $readmemh
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = 48000

# ---------------------------------------------------------------- synth tables
SINE_Q = 4096  # quarter-wave entries (+2 guard entries)
sine_q = [round(32767 * math.sin(math.pi / 2 * i / SINE_Q)) for i in range(SINE_Q + 2)]
sine_q[SINE_Q + 1] = sine_q[SINE_Q]  # guard (never interpolated past the peak)

WT_LEN = 1024
WT_LEVELS = 10      # mip level k serves phase_inc with msb == 20 + k
WT_HARM_LIMIT = 15000.0


def wt_harmonics(k):
    fmax = (2 ** (20 + k + 1)) * FS / 2 ** 32
    return max(1, min(WT_LEN // 2 - 1, int(WT_HARM_LIMIT // fmax)))


def build_wave(kind, nh):
    out = []
    for i in range(WT_LEN):
        x = i / WT_LEN
        s = 0.0
        for n in range(1, nh + 1):
            # Lanczos sigma softens Gibbs ringing (gentler for ambient pads)
            sigma = 1.0 if n == 1 else math.sin(math.pi * n / (nh + 1)) / (math.pi * n / (nh + 1))
            if kind == "saw":
                s += sigma * math.sin(2 * math.pi * n * x) / n
            elif n % 2 == 1:  # tri: odd harmonics, alternating sign, 1/n^2
                s += sigma * (-1) ** ((n - 1) // 2) * math.sin(2 * math.pi * n * x) / (n * n)
        out.append(s)
    return out


def build_wavetables(kind):
    levels = [build_wave(kind, wt_harmonics(k)) for k in range(WT_LEVELS)]
    peak = max(max(abs(v) for v in lv) for lv in levels)
    scale = 0.9 * 32767 / peak  # one scale for all levels keeps loudness consistent
    return [[round(v * scale) for v in lv] for lv in levels]


saw = build_wavetables("saw")
tri = build_wavetables("tri")

# soft limiter: |x| (Q1.23) above knee -> curve tending to ceiling
LIM_KNEE = 0.5
LIM_CEIL = 10 ** (-1.05 / 20)
LIM_ENTRIES = 1024
LIM_SHIFT = 15  # (|x| - knee) >> 15 -> index, covers 4.0 of excess
lim = []
for i in range(LIM_ENTRIES + 1):
    e = (i << LIM_SHIFT) / 2 ** 23
    y = LIM_KNEE + (LIM_CEIL - LIM_KNEE) * math.tanh(e / (LIM_CEIL - LIM_KNEE))
    lim.append(round(y * 2 ** 23))

# ------------------------------------------------------------- composer tables
note_inc = [round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS) for n in range(128)]
cents = [round(2 ** (c / 1200) * 2 ** 30) for c in range(100)]
sine256 = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
log2_64 = [round(math.log2(1 + i / 64) * 65536) for i in range(65)]   # Q16
exp2_64 = [round(2 ** (i / 64) * 2 ** 30) for i in range(65)]         # Q30


def c_array(ctype, name, vals, per_line=12):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


HDR = "/* GENERATED by tools/gen_tables.py - do not edit */\n"


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", newline="\n") as f:
        f.write(text)
    print("wrote", path)


model = [HDR, "#ifndef GEN_TABLES_H\n#define GEN_TABLES_H\n#include <stdint.h>\n",
         f"#define SINE_Q {SINE_Q}\n#define WT_LEN {WT_LEN}\n#define WT_LEVELS {WT_LEVELS}\n"
         f"#define LIM_KNEE {round(LIM_KNEE * 2 ** 23)}\n#define LIM_ENTRIES {LIM_ENTRIES}\n"
         f"#define LIM_SHIFT {LIM_SHIFT}\n",
         c_array("int16_t", "TBL_SINE_Q", sine_q)]
model.append(f"static const int16_t TBL_SAW[{WT_LEVELS}][{WT_LEN}] = {{")
for lv in saw:
    model.append("  {" + ",".join(str(v) for v in lv) + "},")
model.append("};")
model.append(f"static const int16_t TBL_TRI[{WT_LEVELS}][{WT_LEN}] = {{")
for lv in tri:
    model.append("  {" + ",".join(str(v) for v in lv) + "},")
model.append("};")
model.append(c_array("int32_t", "TBL_LIM", lim))
model.append("#endif\n")
write("model/gen_tables.h", "\n".join(model))

comp = [HDR, "#ifndef GEN_CTABLES_H\n#define GEN_CTABLES_H\n#include <stdint.h>\n",
        c_array("uint32_t", "CT_NOTE_INC", note_inc, 8),
        c_array("uint32_t", "CT_CENTS_Q30", cents, 8),
        c_array("int16_t", "CT_SINE256", sine256),
        c_array("uint32_t", "CT_LOG2_Q16", log2_64, 8),
        c_array("uint32_t", "CT_EXP2_Q30", exp2_64, 8),
        "#endif\n"]
write("fw/composer/gen_ctables.h", "\n".join(comp))


def hexfile(path, vals, bits):
    mask = (1 << bits) - 1
    w = (bits + 3) // 4
    write(path, "\n".join(format(v & mask, f"0{w}x") for v in vals) + "\n")


hexfile("src/fpga/core/synth/sine_q.hex", sine_q, 16)
hexfile("src/fpga/core/synth/wt_saw.hex", [v for lv in saw for v in lv], 16)
hexfile("src/fpga/core/synth/wt_tri.hex", [v for lv in tri for v in lv], 16)
hexfile("src/fpga/core/master/lim.hex", lim, 24)
# even/odd banks: one read of each bank yields both interpolation points T[i], T[i+1]
hexfile("src/fpga/core/synth/sine_e.hex", sine_q[0::2], 16)          # T[0], T[2] .. T[4096]
hexfile("src/fpga/core/synth/sine_o.hex", sine_q[1::2], 16)          # T[1], T[3] .. T[4097]
for name, tbl in (("saw", saw), ("tri", tri)):
    hexfile(f"src/fpga/core/synth/wt_{name}_e.hex", [v for lv in tbl for v in lv[0::2]], 16)
    hexfile(f"src/fpga/core/synth/wt_{name}_o.hex", [v for lv in tbl for v in lv[1::2]], 16)
print("harmonics per level:", [wt_harmonics(k) for k in range(WT_LEVELS)])
