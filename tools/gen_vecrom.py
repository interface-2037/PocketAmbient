#!/usr/bin/env python3
"""Build the Phase 3 hardware-test excerpt ROM: composer register writes, recorded by
the C model, replayed into the real audio engine by src/fpga/core/test/vec_player.sv.

    python tools/gen_vecrom.py            (needs build/render)

Outputs
  src/fpga/core/test/vec_rom.hex   64-bit words, one register write each
  src/fpga/core/test/vec_rom.vh    excerpt start addresses and ROM depth
  build/excerpts/<mode>.wav        the same excerpts rendered by the C model, for comparison

Word layout: [63:48] samples since the previous write, [47] FX register, [46:37] address
(voice*32 + reg, or FX reg), [36:5] value, [0] end of excerpt. Gaps longer than 65,535
samples are split with writes to FX register 31 (read-only, ignored by the engine).
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RENDER = os.path.join(ROOT, "build", "render.exe" if os.name == "nt" else "render")
SEED = 123
EXCERPTS = [("drift", 120), ("tides", 90), ("mother", 60), ("hush", 6)]   # seconds
OUT_DIR = os.path.join(ROOT, "src", "fpga", "core", "test")
TMP = os.path.join(ROOT, "build", "excerpts")


def word(delta, fx, addr, val, end=0):
    return (delta << 48) | (fx << 47) | ((addr & 0x3FF) << 37) | ((val & 0xFFFFFFFF) << 5) | end


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(TMP, exist_ok=True)
    words, starts = [], []
    for mode, secs in EXCERPTS:
        prefix = os.path.join(TMP, mode)
        subprocess.run([RENDER, "--mode", mode, "--seed", str(SEED), "--seconds", str(secs),
                        "--fade-end", "--vectors", prefix, "--out", prefix + ".wav", "--quiet"],
                       check=True)
        starts.append(len(words))
        last = 0
        with open(prefix + "_writes.txt") as f:
            for line in f:
                s, fx, idx, val = line.split()
                s, fx, idx, val = int(s, 16), int(fx), int(idx, 16), int(val, 16)
                delta = s - last
                while delta > 0xFFFF:
                    words.append(word(0xFFFF, 1, 31, 0))
                    delta -= 0xFFFF
                words.append(word(delta, fx, idx, val))
                last = s
        total = secs * 48000
        delta = total - last
        while delta > 0xFFFF:
            words.append(word(0xFFFF, 1, 31, 0))
            delta -= 0xFFFF
        words.append(word(delta, 1, 31, 0, end=1))      # end marker: wait out the excerpt
        print(f"{mode}: {secs} s, {len(words) - starts[-1]} words")
    with open(os.path.join(OUT_DIR, "vec_rom.hex"), "w", newline="\n") as f:
        for w in words:
            f.write(f"{w:016x}\n")
    with open(os.path.join(OUT_DIR, "vec_rom.vh"), "w", newline="\n") as f:
        f.write("// GENERATED by tools/gen_vecrom.py - do not edit\n")
        f.write(f"localparam VEC_DEPTH = {len(words)};\n")
        f.write(f"localparam VEC_N = {len(EXCERPTS)};\n")
        for i, (mode, secs) in enumerate(EXCERPTS):
            f.write(f"localparam [13:0] VEC_START_{i} = 14'd{starts[i]};   // {mode}, {secs} s\n")
    print(f"total {len(words)} words ({len(words) * 64 / 1024:.0f} Kbit)")


if __name__ == "__main__":
    sys.exit(main())
