#!/usr/bin/env python3
"""Generate the firmware font: python tools/gen_font.py

  fw/ui/font5x7.c   the square 5x7 font of the UI mockups (tools/ui/mockup.py) for the
                    framebuffer text (fw/ui/fb.c): ASCII 32..95, '|' stored in the '!' slot.
"""
import importlib.util
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("mockup", os.path.join(ROOT, "tools", "ui", "mockup.py"))
mockup = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mockup)
F = mockup.F


def write(path, lines):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


def glyph5(ch):
    g = F.get("|" if ch == "!" else ch, F[" "])
    out = []
    for r in range(7):
        row = g[r] if r < len(g) else ""
        out.append(sum(1 << (4 - i) for i, px in enumerate(row) if px == "#"))
    return out


def write_c_font():
    lines = ["/* GENERATED by tools/gen_font.py from tools/ui/mockup.py - do not edit */",
             "/* 5x7 glyphs for ASCII 32..95, 7 rows each, bit 4 = leftmost column; '!' holds '|' */",
             "#include <stdint.h>", "const uint8_t FONT5X7[64][7] = {"]
    for c in range(32, 96):
        rows = ", ".join(f"0x{b:02x}" for b in glyph5(chr(c)))
        lines.append(f"    {{{rows}}},   /* {c} */")
    lines.append("};")
    write("fw/ui/font5x7.c", lines)


def main():
    write_c_font()


if __name__ == "__main__":
    main()
